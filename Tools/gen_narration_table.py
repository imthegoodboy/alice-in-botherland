"""Write Source/AliceInBotherland/Audio/AIBNarrationLines.inl from SourceAssets/Audio/narration.json + narration_durations.json.
Run after Tools/gen_voice.py so captions and timings always match the recorded lines."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines = json.load(open(os.path.join(ROOT, "SourceAssets", "Audio", "narration.json"), encoding="utf-8"))["lines"]
durations = json.load(open(os.path.join(ROOT, "SourceAssets", "Audio", "narration_durations.json"), encoding="utf-8"))
out = ["// Generated by Tools/gen_narration_table.py from SourceAssets/Audio/narration.json - do not edit by hand.",
       "// AIB_NARRATION_LINE(Id, SpokenSeconds, Caption)"]
for line_id, text in lines.items():
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'AIB_NARRATION_LINE({line_id}, {durations.get(line_id, 3.0):.2f}f, "{escaped}")')
path = os.path.join(ROOT, "Source", "AliceInBotherland", "Audio", "AIBNarrationLines.inl")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", path, len(lines), "lines")
