"""Record the champions' last words (spoken before the Guardian's judgement) with ElevenLabs and write the caption table.
usage: gen_last_words.py [ids...]   (default: every line in SourceAssets/Audio/last_words.json that has no WAV yet)
Reads ElevenLabs keys from the project .env (never printed). Needs ffmpeg/ffprobe (FFMPEG / FFPROBE env or on PATH).
Writes SourceAssets/Audio/VO/LW_*.wav and Source/AliceInBotherland/Audio/AIBLastWordsLines.inl."""
import json, os, subprocess, sys, urllib.error, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FFMPEG = os.environ.get("FFMPEG", "ffmpeg")
FFPROBE = os.environ.get("FFPROBE", "ffprobe")
OUT = os.path.join(ROOT, "SourceAssets", "Audio", "VO")
env = {}
for line in open(os.path.join(ROOT, ".env"), encoding="utf-8", errors="replace"):
    if "=" in line and not line.strip().startswith("#"):
        k, v = line.split("=", 1)
        env[k.strip()] = v.strip().strip('"').strip("'")
keys = [env[k] for k in ("ELEVENLABS_API_KEY1", "ELEVENLABS_API_KEY2", "ELEVENLABS_API_KEY3", "ELEVENLABS_API_KEY4", "ELEVENLABS_API_KEY") if env.get(k)]
script = json.load(open(os.path.join(ROOT, "SourceAssets", "Audio", "last_words.json"), encoding="utf-8"))
lines = script["lines"]
ids = sys.argv[1:] or [i for i in lines if not os.path.exists(os.path.join(OUT, i + ".wav"))]
key_index = 0


def tts(text):
    global key_index
    body = {"text": text, "model_id": "eleven_multilingual_v2", "voice_settings": script["settings"]}
    while key_index < len(keys):
        req = urllib.request.Request(f"https://api.elevenlabs.io/v1/text-to-speech/{script['voice_id']}?output_format=mp3_44100_128",
                                     data=json.dumps(body).encode(), method="POST",
                                     headers={"xi-api-key": keys[key_index], "Content-Type": "application/json", "Accept": "audio/mpeg"})
        try:
            return urllib.request.urlopen(req, timeout=120).read()
        except urllib.error.HTTPError as e:
            msg = e.read()[:200].decode(errors="replace")
            if e.code in (401, 402, 403, 429) or "quota" in msg.lower():
                print(f"  key #{key_index + 1} unavailable ({e.code}), switching", flush=True)
                key_index += 1
                continue
            raise RuntimeError(f"HTTP {e.code} {msg}")
    raise RuntimeError("all ElevenLabs keys exhausted")


for line_id in ids:
    mp3 = os.path.join(OUT, line_id + ".mp3")
    wav = os.path.join(OUT, line_id + ".wav")
    open(mp3, "wb").write(tts(lines[line_id]))
    # Same treatment as the narrator, a touch quieter: these are spoken, not announced.
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-i", mp3, "-af",
                    "highpass=f=70,loudnorm=I=-18:TP=-1.5:LRA=9,adelay=150", "-ac", "1", "-ar", "48000", "-c:a", "pcm_s16le", wav], check=True)
    os.remove(mp3)
    print("ok", line_id, flush=True)

out = ["// Generated by Tools/gen_last_words.py from SourceAssets/Audio/last_words.json - do not edit by hand.",
       "// AIB_LAST_WORDS(Id, SpokenSeconds, Caption)"]
for line_id, text in lines.items():
    wav = os.path.join(OUT, line_id + ".wav")
    seconds = 4.0
    if os.path.exists(wav):
        seconds = float(subprocess.run([FFPROBE, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", wav],
                                       capture_output=True, text=True).stdout.strip())
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'AIB_LAST_WORDS({line_id}, {seconds:.2f}f, "{escaped}")')
path = os.path.join(ROOT, "Source", "AliceInBotherland", "Audio", "AIBLastWordsLines.inl")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", path, len(lines), "lines")
